// scripts/e2e/map-history-fixture.mjs -- a project with a history of committed maps, for the sheet of the map in the
// window (TESTS/sheets/map-views.sheet.lua): the comparison of maps (`shape/<sha>`) needs commits whose map differs
// from the one on disk, and this checkout commits no map of its own.
//
//   node scripts/e2e/map-history-fixture.mjs
//
// Writes src-tauri/target/sheet-fixtures/map-history/project, fresh on every call (under the build folder and not the
// temp folder, for the reason rules/tab.rs gives: the standalone engine does not come back from a project below
// AppData\Local\Temp on Windows). A small Lua project in two commits, each map generated by the engine of this
// checkout (src-tauri/binaries) and committed with it:
//
//   OLDER  lua/app (requires app.core), app.core (requires app.core.store), app.core.store (requires app.core.cache),
//          app.core.cache, app.log (requires nothing, required by nothing)
//   NEWER  app.core.cache is gone; app.util is new and lua/app requires it. The map on disk is this one.
//
// So OLDER against the map on disk is one node added (lua/app/util.lua), one lost (lua/app/core/cache.lua), one
// require gained (app -> app.util) and one lost (store -> cache). app.log takes part in none of it: without a node
// the comparison leaves alone, every box is marked and the page has no rest to dim (map-compare's "the rest is
// dimmed" failed on exactly that once the engine answered).
//
// git runs without the global and system configuration of whoever runs this (GIT_CONFIG_GLOBAL is a file of the
// fixture's own): a fixture commit carries no person's name and asks for no signing key.
//
// Exit 0: written. Exit 1: no engine or no git, or a step failed (what it said is printed).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const dest = join(root, 'src-tauri', 'target', 'sheet-fixtures', 'map-history');
const project = join(dest, 'project');

const fail = (why) => {
  console.error(`map-history-fixture: ${why}`);
  process.exit(1);
};

const bins = join(root, 'src-tauri', 'binaries');
const engine = existsSync(bins)
  ? readdirSync(bins)
      .filter((n) => n.startsWith('docmap-'))
      .map((n) => join(bins, n))
      .find((p) => statSync(p).size > 0)
  : undefined;
if (!engine) fail(`no engine in ${bins}: stage one first (scripts/build-install.ps1 -BuildOnly does)`);

rmSync(dest, { recursive: true, force: true });
mkdirSync(project, { recursive: true });
const gitconfig = join(dest, 'gitconfig');
writeFileSync(gitconfig, '[user]\n\tname = Sheet Fixture\n\temail = sheet@example.invalid\n[commit]\n\tgpgsign = false\n');
const gitEnv = { ...process.env, GIT_CONFIG_GLOBAL: gitconfig, GIT_CONFIG_NOSYSTEM: '1' };

function run(program, args, env) {
  const r = spawnSync(program, args, { cwd: project, encoding: 'utf8', env, timeout: 600_000 });
  if (r.error || r.status !== 0) {
    fail(`${program} ${args.join(' ')}: ${r.error ?? ''}${r.stdout ?? ''}${r.stderr ?? ''}`);
  }
  return r.stdout;
}
const git = (...args) => run('git', args, gitEnv);

/** A module: its `---@module` name and what it requires. */
function module(file, name, requires) {
  const path = join(project, file);
  mkdirSync(dirname(path), { recursive: true });
  const lines = [`---@module '${name}'`];
  requires.forEach((r, i) => lines.push(`local dep${i} = require("${r}")`));
  lines.push('local M = {}', 'function M.run()', '  return true', 'end', 'return M', '');
  writeFileSync(path, lines.join('\n'));
}

/** The map of the tree as it is, by the engine, committed with the sources. */
function commit(message) {
  run(engine, [project], process.env);
  if (!existsSync(join(project, 'docs', 'map', 'module_map.json'))) fail('the engine wrote no docs/map/module_map.json');
  git('add', '-A');
  git('commit', '-q', '-m', message);
}

git('init', '-q', '-b', 'main');
// a layering rule, so the Layers view has bands to draw
writeFileSync(
  join(project, '.docmap.json'),
  JSON.stringify({ layers: [{ from: 'app.core', to: 'app.util', why: 'the core knows no helpers' }] }, null, 2) + '\n'
);
module('lua/app/init.lua', 'app', ['app.core']);
module('lua/app/core/init.lua', 'app.core', ['app.core.store']);
module('lua/app/core/store.lua', 'app.core.store', ['app.core.cache']);
module('lua/app/core/cache.lua', 'app.core.cache', []);
module('lua/app/log.lua', 'app.log', []);
commit('older: app, core, store, cache');

rmSync(join(project, 'lua', 'app', 'core', 'cache.lua'));
module('lua/app/core/store.lua', 'app.core.store', []);
module('lua/app/util.lua', 'app.util', []);
module('lua/app/init.lua', 'app', ['app.core', 'app.util']);
commit('newer: util instead of cache');

console.log(`map-history-fixture: ${project} (${git('rev-list', '--count', 'HEAD').trim()} commits)`);
