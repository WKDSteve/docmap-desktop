// scripts/e2e/telemetry-fixture.mjs -- a Lua project with a map that has functions, for the sheet of the runtime detail
// in the window (TESTS/sheets/runtime-detail.sheet.lua).
//
//   node scripts/e2e/telemetry-fixture.mjs
//
// Writes src-tauri/target/sheet-fixtures/telemetry/project, fresh on every call (below the build folder, not the temp
// folder: the standalone engine does not come back from a project below AppData\Local\Temp on Windows, see
// map-history-fixture.mjs). Two modules, as docmap.nvim's lookup_page fixture has them:
//
//   look         M.start
//   look.store   M.load, M.old_load
//
// and a `.docmap.json` that names the telemetry namespace the sheet's store is written under
// (`telemetry_namespace`; telemetry-store.lua writes it, `prepare` of the app `window-telemetry`). The map is
// generated by the engine of this checkout *with the grammars of this checkout* (DOCMAP_TS_DIR, as the app passes
// them): without a grammar the map has modules and no functions, and there is nothing to select.
//
// Exit 0: written. Exit 1: no engine or no grammars, or the engine failed (what it said is printed).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const NAMESPACE = 'docmap-sheet-telemetry';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const dest = join(root, 'src-tauri', 'target', 'sheet-fixtures', 'telemetry');
const project = join(dest, 'project');

const fail = (why) => {
  console.error(`telemetry-fixture: ${why}`);
  process.exit(1);
};

const bins = join(root, 'src-tauri', 'binaries');
const engine = existsSync(bins)
  ? readdirSync(bins)
      .filter((n) => n.startsWith('docmap-'))
      .map((n) => join(bins, n))
      .find((p) => statSync(p).size > 0)
  : undefined;
if (!engine) fail(`no engine in ${bins}: stage one first (scripts/build-install.ps1 -BuildOnly does)`);
const grammars = join(root, 'src-tauri', 'resources', 'grammars');
if (!existsSync(grammars)) fail(`no grammars in ${grammars}: without them the map has no functions`);

rmSync(dest, { recursive: true, force: true });
mkdirSync(join(project, 'lua', 'look'), { recursive: true });

writeFileSync(join(project, '.docmap.json'), JSON.stringify({ telemetry_namespace: NAMESPACE, source: 'lua' }, null, 2) + '\n');
writeFileSync(
  join(project, 'lua', 'look', 'init.lua'),
  [
    "---@module 'look'",
    'local store = require("look.store")',
    'local M = {}',
    '',
    '---Starts it.',
    '---@param key string',
    '---@return string',
    'function M.start(key)',
    '  return store.load(key)',
    'end',
    '',
    'return M',
    '',
  ].join('\n')
);
writeFileSync(
  join(project, 'lua', 'look', 'store.lua'),
  [
    "---@module 'look.store'",
    'local M = {}',
    '',
    '---Loads a key.',
    '---@param key string',
    '---@return string',
    'function M.load(key)',
    '  return key',
    'end',
    '',
    '---The old way to load a key.',
    '---@param key string',
    '---@return string',
    'function M.old_load(key)',
    '  return M.load(key)',
    'end',
    '',
    'return M',
    '',
  ].join('\n')
);

const r = spawnSync(engine, [project], {
  cwd: project,
  encoding: 'utf8',
  env: { ...process.env, DOCMAP_TS_DIR: grammars },
  timeout: 600_000,
});
if (r.error || r.status !== 0) fail(`${engine}: ${r.error ?? ''}${r.stdout ?? ''}${r.stderr ?? ''}`);
const mapFile = join(project, 'docs', 'map', 'module_map.json');
if (!existsSync(mapFile)) fail('the engine wrote no docs/map/module_map.json');
console.log(`telemetry-fixture: ${project}`);
